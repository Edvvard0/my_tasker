/// К чему применить правку или удаление повторяющегося события (02, 5.1.4;
/// spec 5.4).
enum RecurrenceScope {
  /// Только этот экземпляр.
  only('Только это'),

  /// Этот и следующие: серия разрезается.
  following('Это и следующие'),

  /// Все экземпляры серии.
  all('Все в серии');

  const RecurrenceScope(this.label);

  final String label;
}
